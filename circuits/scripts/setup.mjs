// Circuit build + Groth16 setup + Solidity verifier export.
//
//   node circuits/scripts/setup.mjs            compile, download ptau, setup, export verifier
//   (or `npm run circuits:setup` from backend/; needs `npm install` there for snarkjs + circomlib)
//   SETUP_LOCAL_PTAU=1 node ...                generate a local (non-ceremony) ptau instead
//   PTAU_URL=... node ...                      use another phase-1 file (must be >= 2^15)
//
// Phase 1 is the PSE Perpetual Powers of Tau (a real multi-party ceremony). Phase 2 is a
// single random contribution plus a beacon: a HACKATHON setup, not a production ceremony.
import { execFileSync } from "node:child_process";
import { createWriteStream, existsSync, mkdirSync, readFileSync, renameSync, rmSync, statSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { randomBytes } from "node:crypto";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { Readable } from "node:stream";
import { pipeline } from "node:stream/promises";

const here = dirname(fileURLToPath(import.meta.url));
const circuits = resolve(here, "..");
const root = resolve(circuits, "..");
// node dependencies (snarkjs, circomlib) and the circom binary live under backend/
const backend = join(root, "backend");
const build = join(circuits, "build");
const ptauDir = join(build, "ptau");
const PTAU_POWER = 15;
const PTAU_URL = process.env.PTAU_URL ?? `https://pse-trusted-setup-ppot.s3.eu-central-1.amazonaws.com/pot28_0080/ppot_0080_${PTAU_POWER}.ptau`;
const ptauFile = join(ptauDir, `phase1_${PTAU_POWER}.ptau`);

const require = createRequire(join(backend, "package.json"));
const snarkjsCli = join(dirname(require.resolve("snarkjs")), "cli.cjs");
const exe = process.platform === "win32" ? ".exe" : "";
const circom = existsSync(join(backend, ".tools", "bin", `circom${exe}`)) ? join(backend, ".tools", "bin", `circom${exe}`) : "circom";

function snarkjs(...args) {
  console.log(`> snarkjs ${args.join(" ")}`);
  execFileSync(process.execPath, [snarkjsCli, ...args], { stdio: "inherit", cwd: circuits });
}

async function download(url, dest) {
  console.log(`downloading ${url}`);
  const res = await fetch(url);
  if (!res.ok || !res.body) throw new Error(`download failed: HTTP ${res.status}`);
  await pipeline(Readable.fromWeb(res.body), createWriteStream(`${dest}.part`));
  renameSync(`${dest}.part`, dest);
}

mkdirSync(ptauDir, { recursive: true });

// 1. compile
console.log("> circom spend.circom");
execFileSync(circom, ["spend.circom", "--r1cs", "--wasm", "--sym", "--O2", "-o", "build", "-l", join(backend, "node_modules")], { stdio: "inherit", cwd: circuits });

// 2. phase 1
if (!existsSync(ptauFile)) {
  if (process.env.SETUP_LOCAL_PTAU === "1") {
    const p0 = join(ptauDir, "local_0000.ptau");
    const p1 = join(ptauDir, "local_0001.ptau");
    snarkjs("powersoftau", "new", "bn128", String(PTAU_POWER), p0);
    snarkjs("powersoftau", "contribute", p0, p1, "--name=sealed-local", `-e=${randomBytes(32).toString("hex")}`);
    snarkjs("powersoftau", "prepare", "phase2", p1, ptauFile);
  } else {
    await download(PTAU_URL, ptauFile);
  }
}
console.log(`ptau: ${ptauFile} (${(statSync(ptauFile).size / 1e6).toFixed(1)} MB)`);

// 3. phase 2 (circuit specific)
const z0 = join(build, "spend_0000.zkey");
const zFinal = join(build, "spend_final.zkey");
snarkjs("groth16", "setup", join(build, "spend.r1cs"), ptauFile, z0);
const z1 = join(build, "spend_0001.zkey");
snarkjs("zkey", "contribute", z0, z1, "--name=sealed-hackathon-1", `-e=${randomBytes(32).toString("hex")}`);
snarkjs("zkey", "beacon", z1, zFinal, randomBytes(32).toString("hex"), "10", "-n=sealed-final-beacon");
snarkjs("zkey", "verify", join(build, "spend.r1cs"), ptauFile, zFinal);
snarkjs("zkey", "export", "verificationkey", zFinal, join(build, "verification_key.json"));

// 4. Solidity verifier: generated by snarkjs; only the contract name and header are changed by this script.
const solOut = join(root, "contracts", "src", "SpendVerifier.sol");
mkdirSync(dirname(solOut), { recursive: true });
const tmpSol = join(build, "verifier.sol");
snarkjs("zkey", "export", "solidityverifier", zFinal, tmpSol);
const sol = readFileSync(tmpSol, "utf8").replace(/contract Groth16Verifier/, "contract SpendVerifier");
writeFileSync(
  solOut,
  `// GENERATED by circuits/scripts/setup.mjs from snarkjs (zkey export solidityverifier). Do not hand-edit.\n` +
    `// Phase 1: ${PTAU_URL.split("/").pop()}. Phase 2: hackathon setup (one random contribution + beacon), not a ceremony.\n` +
    sol,
);
for (const f of [z0, z1, tmpSol]) rmSync(f, { force: true });
console.log(`wrote ${solOut}`);
