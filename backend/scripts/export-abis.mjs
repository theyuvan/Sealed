// Copies contract ABIs from contracts/out into packages/core/src/abi.ts (run after `forge build`).
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { REPO, ROOT } from "./lib.mjs";

const contracts = {
  mandateRegistryAbi: "MandateRegistry.sol/MandateRegistry.json",
  sessionEscrowAbi: "SessionEscrow.sol/SessionEscrow.json",
  devTokenAbi: "DevEIP3009Token.sol/DevEIP3009Token.json",
};

let out = "// GENERATED by scripts/export-abis.mjs from contracts/out. Do not edit.\n\n";
for (const [name, file] of Object.entries(contracts)) {
  const { abi } = JSON.parse(readFileSync(join(REPO, "contracts", "out", file), "utf8"));
  out += `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
// The pinned production token is only assumed to implement ERC-20 + EIP-3009.
out += `export const eip3009Abi = [
  { type: "function", name: "authorizationState", stateMutability: "view", inputs: [{ name: "authorizer", type: "address" }, { name: "nonce", type: "bytes32" }], outputs: [{ type: "bool" }] },
  { type: "function", name: "transferWithAuthorization", stateMutability: "nonpayable", inputs: [{ name: "from", type: "address" }, { name: "to", type: "address" }, { name: "value", type: "uint256" }, { name: "validAfter", type: "uint256" }, { name: "validBefore", type: "uint256" }, { name: "nonce", type: "bytes32" }, { name: "signature", type: "bytes" }], outputs: [] },
  { type: "function", name: "balanceOf", stateMutability: "view", inputs: [{ name: "a", type: "address" }], outputs: [{ type: "uint256" }] },
  { type: "function", name: "name", stateMutability: "view", inputs: [], outputs: [{ type: "string" }] },
  { type: "function", name: "version", stateMutability: "view", inputs: [], outputs: [{ type: "string" }] },
  { type: "function", name: "decimals", stateMutability: "view", inputs: [], outputs: [{ type: "uint8" }] },
  { type: "function", name: "symbol", stateMutability: "view", inputs: [], outputs: [{ type: "string" }] },
  { type: "event", name: "Transfer", anonymous: false, inputs: [{ name: "from", type: "address", indexed: true }, { name: "to", type: "address", indexed: true }, { name: "value", type: "uint256", indexed: false }] },
  { type: "event", name: "AuthorizationUsed", anonymous: false, inputs: [{ name: "authorizer", type: "address", indexed: true }, { name: "nonce", type: "bytes32", indexed: true }] },
] as const;
`;
writeFileSync(join(ROOT, "packages", "core", "src", "abi.ts"), out);
console.log("wrote packages/core/src/abi.ts");
