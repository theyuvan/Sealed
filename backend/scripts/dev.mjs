// One-command local stack:
//   anvil -> deploy contracts -> fund dev wallets -> HSP local stand-in, coordinator, vault, sellers, buyer agent
//
// Dev keys are generated once into .env.local (gitignored) and never printed. Everything here is local:
// the HSP side is the "HSP local stand-in", not HashKey.
import { existsSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { randomBytes } from "node:crypto";
import { join } from "node:path";
import { REPO, ROOT, run, rpcUp, start, tool, waitFor } from "./lib.mjs";

const RPC = "http://127.0.0.1:8545";
const envLocal = join(ROOT, ".env.local");
const children = [];

function parseEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = /^([A-Z0-9_]+)=(.*)$/.exec(line.trim());
    if (m) out[m[1]] = m[2];
  }
  return out;
}

const hex32 = () => `0x${randomBytes(32).toString("hex")}`;

// 1. toolchain + circuit artifacts
if (!existsSync(join(ROOT, ".tools", "bin", process.platform === "win32" ? "forge.exe" : "forge"))) run(process.execPath, [join(ROOT, "scripts", "install-tools.mjs")]);
if (!existsSync(join(REPO, "circuits", "build", "spend_final.zkey"))) run(process.execPath, [join(REPO, "circuits", "scripts", "setup.mjs")]);

// 2. dev env (.env.local)
const { privateKeyToAccount } = await import("viem/accounts");
const { createECDH } = await import("node:crypto");
let env = existsSync(envLocal) ? parseEnv(readFileSync(envLocal, "utf8")) : {};
const keyNames = [
  "DEPLOYER_PRIVATE_KEY",
  "COORDINATOR_PRIVATE_KEY",
  "VAULT_PRIVATE_KEY",
  "BUYER_WALLET_PRIVATE_KEY",
  "SELLER_1_PRIVATE_KEY",
  "SELLER_2_PRIVATE_KEY",
  "ROGUE_PRIVATE_KEY",
  "HSP_STANDIN_RELAYER_PRIVATE_KEY",
  "HSP_MERCHANT_PRIVATE_KEY",
  "ROGUE_HSP_MERCHANT_PRIVATE_KEY",
];
for (const k of keyNames) env[k] ??= hex32();
for (const k of ["VAULT_ADMIN_TOKEN", "VAULT_AGENT_TOKEN", "HSP_APP_SECRET", "HSP_WEBHOOK_SECRET", "ROGUE_HSP_APP_SECRET"]) env[k] ??= randomBytes(24).toString("hex");
env.HSP_APP_KEY ??= `dev-${randomBytes(6).toString("hex")}`;
env.ROGUE_HSP_APP_KEY ??= `rogue-${randomBytes(6).toString("hex")}`;
if (!env.AUDITOR_PUBLIC_KEY) {
  const e = createECDH("secp256k1");
  e.generateKeys();
  env.AUDITOR_PUBLIC_KEY = `0x${e.getPublicKey("hex")}`;
  env.AUDITOR_PRIVATE_KEY = `0x${e.getPrivateKey("hex")}`; // dev only, to decrypt with scripts/auditor-decrypt
}
Object.assign(env, {
  CHAIN_ID: "31337",
  HSK_RPC_URL: RPC,
  HSP_LOCAL_STANDIN: "1",
  HSP_STANDIN_URL: "http://127.0.0.1:7301",
  HSP_MERCHANT_NAME: "Sealed (dev)",
  COORDINATOR_ADDRESS: privateKeyToAccount(env.COORDINATOR_PRIVATE_KEY).address,
  VAULT_RESPONSE_DELAY_MS: env.VAULT_RESPONSE_DELAY_MS ?? "1500",
});
writeFileSync(envLocal, `# generated by scripts/dev.mjs for the LOCAL anvil chain only. Do not use these keys anywhere else.\n${Object.entries(env).map(([k, v]) => `${k}=${v}`).join("\n")}\n`);

// 3. anvil
if (!(await rpcUp(RPC).catch(() => false))) {
  // fresh chain: local service state from a previous run would point at contracts that no longer exist
  const data = join(ROOT, "data");
  if (existsSync(data)) for (const f of readdirSync(data)) if (f.includes("-31337.sqlite")) rmSync(join(data, f), { force: true });
  children.push(start(tool("anvil"), ["--port", "8545", "--silent"], { stdio: "ignore" }));
  await waitFor(() => rpcUp(RPC), { what: "anvil" });
}
const rpc = (method, params) => fetch(RPC, { method: "POST", headers: { "content-type": "application/json" }, body: JSON.stringify({ jsonrpc: "2.0", id: 1, method, params }) });
for (const k of keyNames.filter((k) => !k.includes("MERCHANT"))) await rpc("anvil_setBalance", [privateKeyToAccount(env[k]).address, "0x56BC75E2D63100000"]);

// 4. deploy (dev token, verifier, registry, escrow)
const childEnv = { ...process.env, ...env };
delete childEnv.PINNED_TOKEN;
run(tool("forge"), ["script", "script/Deploy.s.sol", "--rpc-url", RPC, "--broadcast", "--silent"], { cwd: join(REPO, "contracts"), env: childEnv });
const deployment = JSON.parse(readFileSync(join(REPO, "contracts", "deployments", "31337.json"), "utf8"));
console.log("deployed:", deployment);

// 5. fund the buyer with dev stablecoin
run(process.execPath, ["--import", "tsx", join(ROOT, "scripts", "fund.ts"), "--local"], { env: childEnv });

// 6. services
const svc = [
  ["hsp-standin", "services/hsp-standin/src/main.ts"],
  ["coordinator", "services/coordinator/src/main.ts"],
  ["vault", "services/vault/src/main.ts"],
  ["sellers", "services/sellers/src/main.ts"],
  ["buyer-agent", "services/buyer-agent/src/main.ts"],
];
for (const [name, file] of svc) {
  const p = start(process.execPath, ["--import", "tsx", join(ROOT, file)], { env: childEnv, stdio: ["ignore", "pipe", "pipe"] });
  const tag = `[${name}]`.padEnd(14);
  p.stdout.on("data", (d) => process.stdout.write(d.toString().split("\n").filter(Boolean).map((l) => `${tag} ${l}\n`).join("")));
  p.stderr.on("data", (d) => process.stderr.write(d.toString().split("\n").filter(Boolean).map((l) => `${tag} ${l}\n`).join("")));
  children.push(p);
}
for (const port of [7301, 7201, 7001, 7101, 7102, 7103, 7002]) {
  await waitFor(async () => (await fetch(`http://127.0.0.1:${port}/health`)).ok, { what: `service on :${port}`, timeoutMs: 60_000 });
}
console.log(`
Sealed dev stack is up (local anvil, HSP local stand-in):
  vault        http://127.0.0.1:7001   (admin token + agent token in .env.local)
  buyer-agent  http://127.0.0.1:7002
  sellers      http://127.0.0.1:7101 (honest-1)  :7102 (honest-2)  :7103 (rogue)
  coordinator  http://127.0.0.1:7201
  HSP stand-in http://127.0.0.1:7301
Run the full flow in another terminal:  npm run e2e
Ctrl+C to stop.`);

const stop = () => {
  for (const c of children) c.kill();
  process.exit(0);
};
process.on("SIGINT", stop);
process.on("SIGTERM", stop);
